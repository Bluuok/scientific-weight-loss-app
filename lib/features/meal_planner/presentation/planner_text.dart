String plannerErrorText(Object error) {
  final text = error.toString();
  if (RegExp(r'[\u4e00-\u9fff]').hasMatch(text)) return text;
  if (text.contains('429')) return '请求较频繁，请稍后重试。';
  if (text.contains('401') || text.contains('403')) return '服务拒绝访问，请检查密钥和权限。';
  if (text.toLowerCase().contains('timeout')) return '请求超时，请检查网络后重试。';
  if (text.contains('Cancelled')) return '已取消。';
  return '操作未完成，请检查网络、资料或配置后重试。';
}
